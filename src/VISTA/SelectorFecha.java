    private static final String[] DIAS = {"Lu", "Ma", "Mi", "Ju", "Vi", "Sa", "Do"};

    private LocalDate seleccion;     // fecha elegida (null = cancelado)
    private LocalDate marcada;       // fecha que se resalta al abrir

    public SelectorFecha(java.awt.Frame parent, boolean modal) {
        this((java.awt.Window) parent, LocalDate.now());
    }

    private SelectorFecha(java.awt.Window dueno, LocalDate inicial) {
        super(dueno, "Seleccione la fecha", java.awt.Dialog.ModalityType.APPLICATION_MODAL);
        this.marcada = inicial == null ? LocalDate.now() : inicial;
        initComponents();
        configurarCalendario();
        setLocationRelativeTo(dueno);
    }

    private void configurarCalendario() {
        ((javax.swing.JComponent) getContentPane()).setBorder(
                javax.swing.BorderFactory.createEmptyBorder(8, 8, 8, 8));
        cmbMes.removeAllItems();
        for (int m = 1; m <= 12; m++) {
            String n = java.time.Month.of(m).getDisplayName(TextStyle.FULL, Locale.forLanguageTag("es"));
            cmbMes.addItem(Character.toUpperCase(n.charAt(0)) + n.substring(1));
        }
        cmbMes.setSelectedIndex(marcada.getMonthValue() - 1);
        spnAno.setValue(marcada.getYear());
        spnAno.setEditor(new JSpinner.NumberEditor(spnAno, "#"));

        cmbMes.addActionListener(e -> pintarDias());
        spnAno.addChangeListener(e -> pintarDias());

        pintarDias();
        pack();
    }

    private void moverMes(int delta) {
        YearMonth ym = YearMonth.of((Integer) spnAno.getValue(), cmbMes.getSelectedIndex() + 1).plusMonths(delta);
        spnAno.setValue(ym.getYear());          // dispara pintarDias()
        cmbMes.setSelectedIndex(ym.getMonthValue() - 1);
    }

    private void pintarDias() {
        if (cmbMes.getItemCount() < 12) {
            return;
        }
        panelDias.removeAll();
        for (String d : DIAS) {
            panelDias.add(new JLabel(d, SwingConstants.CENTER));
        }
        YearMonth ym = YearMonth.of((Integer) spnAno.getValue(), cmbMes.getSelectedIndex() + 1);
        int hueco = ym.atDay(1).getDayOfWeek().getValue() - 1;   // lunes = 0
        for (int i = 0; i < hueco; i++) {
            panelDias.add(new JLabel(""));
        }
        for (int d = 1; d <= ym.lengthOfMonth(); d++) {
            final LocalDate f = ym.atDay(d);
            JButton b = new JButton(String.valueOf(d));
            b.setName("dia" + d);
            b.setMargin(new java.awt.Insets(2, 2, 2, 2));
            if (f.equals(marcada)) {
                b.setBackground(new java.awt.Color(180, 205, 255));
            }
            b.addActionListener(e -> {
                seleccion = f;
                dispose();
            });
            panelDias.add(b);
        }
        panelDias.revalidate();
        panelDias.repaint();
        if (isDisplayable()) {
            pack();
        }
    }

    /** Muestra el calendario; devuelve la fecha elegida o null si se cancela. */
    public static LocalDate elegir(Component padre, LocalDate inicial) {
        java.awt.Window w = (padre instanceof java.awt.Window ventana) ? ventana
                : (padre == null ? null : SwingUtilities.getWindowAncestor(padre));
        SelectorFecha s = new SelectorFecha(w, inicial == null ? LocalDate.now() : inicial);
        s.setVisible(true);          // modal: vuelve al cerrarse
        return s.seleccion;
    }

